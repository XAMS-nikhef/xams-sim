#!/usr/bin/env python3
"""Write the COMSOL model of the XAMS TPC electric field as a Java file (COMSOL 6.2 API), from geometry.yaml and
efield/cases.yaml. Build and solve it with efield/comsol/run.sh (compile + comsol batch); the result is an .mph you can
open in the COMSOL GUI with geometry, materials, physics, mesh, study (one auxiliary sweep over all cases) and plots in
place.

Model (3D, mm, z = 0 at the gate, frame as geometry.yaml; SiPM azimuths in the data x-y frame):
- domain: inside of the grounded inner cryostat vessel; PTFE bucket with liquid xenon up to the level, gas elsewhere;
- meshes (top screen, anode, gate, cathode, bottom screen) as solid conducting discs r < 36 mm (the etched holes are
  not resolved) plus their support rings (r 36-46.3 mm, on the side given by foil_side);
- inner PTFE cylinder (r 31-36 mm, top against the gate, 0.875 mm gap above the cathode), copper field-shaping rings
  at the resistor-chain potentials, PTFE PMT holders, PMTs as conducting boxes at their HV;
- SiPMs: grounded 3 x 3 mm planes at the bottom of 1 mm deep square holes in the PTFE inner wall;
- dielectric constants: LXe 1.96, GXe 1.00, PTFE 2.1.
Checks (printed as CHECK lines, parsed by run.sh -> results/efield/checks.json): drift field at the centre against
(V_gate - V_cathode) / 51.8 mm, liquid / gas field ratio in the extraction gap, potential at the SiPM height near the
wall, field in the SiPM hole.

    python efield/comsol/make_model.py [--hmax-tpc 1.5] [--hmax-sipm 0.25] [--no-sipm] [--cases sept,cma,cmb]
"""
import argparse
import math
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
BUILD = ROOT / "efield" / "comsol" / "build"
OUTDIR = ROOT / "results" / "efield" / "comsol"
CLASS = "XAMS_efield"


def jstr(a):
    return "new String[]{" + ", ".join(f'"{x}"' for x in a) + "}"


def jdbl(a):
    return "new double[]{" + ", ".join(f"{x:.6g}" for x in a) + "}"


class J:
    """collects Java statements"""

    def __init__(self):
        self.lines = []

    def __call__(self, s=""):
        self.lines.append("    " + s if s else "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hmax-tpc", type=float, default=1.5, help="max element size inside the TPC [mm]")
    ap.add_argument("--hmax-sipm", type=float, default=0.25, help="max element size in the SiPM holes [mm]")
    ap.add_argument("--hmax", type=float, default=8.0, help="global max element size [mm]")
    ap.add_argument("--no-sipm", action="store_true", help="leave the SiPMs out (axisymmetric reference)")
    ap.add_argument("--cases", default="", help="comma-separated subset of cases.yaml (default: all)")
    a = ap.parse_args()

    G = yaml.safe_load(open(ROOT / "geometry.yaml"))
    C = yaml.safe_load(open(ROOT / "efield" / "cases.yaml"))
    cases = C["cases"]
    if a.cases:
        cases = {k: cases[k] for k in a.cases.split(",")}
    names = list(cases)

    # ---------------------------------------------------------------- geometry numbers
    mc = G["mesh_common"]
    r_bore = mc["ring"]["inner_diameter_mm"] / 2            # 36
    r_ring = mc["ring"]["outer_diameter_mm"] / 2            # 46.3
    t_ring = mc["ring"]["thickness_mm"] - mc["foil_thickness_mm"] / 2   # body from the foil mid-plane: 1.725
    meshes = {m["name"]: m for m in G["meshes"]}
    zc = meshes["cathode"]["z_mm"]
    pt = G["ptfe_cylinder"]
    r_ptfe_out = 36.0
    r_ptfe_in = r_ptfe_out - pt["wall_thickness_mm"]        # 31
    z_ptfe_bot = -50.925                                     # 0.875 mm above the cathode mid-plane (geometry.yaml)
    fsr = G["field_shaping_rings"]
    t_fsr = fsr["thickness_mm"]
    level = C["liquid_level_mm"]
    bk = G["ptfe_bucket"]
    rim = level + bk["weir_below_rim_mm"]
    bk_bottom = rim - bk["height_mm"]
    bk_t = bk["bottom_thickness_mm"] or 10.0
    ves = G["cryostat_vessel"]
    r_ves = ves["inner_diameter_mm"] / 2
    ves_bot = bk_bottom - (ves["bottom_gap_mm"] or 10.0)
    wall = (ves["outer_diameter_mm"] - ves["inner_diameter_mm"]) / 2
    ves_h = ves["height_mm"] - 2 * (ves["end_thickness_mm"] or wall)
    pmt = G["pmt_common"]
    s_pmt, h_pmt = pmt["outer_square_mm"], pmt["height_mm"]
    pz = {p["name"]: p["window_z_mm"] for p in G["pmts"]}
    ph = G["pmt_ptfe"]
    ap50 = ph["aperture_square_mm"]
    sp = C["sipm"]

    j = J()
    j('Model model = ModelUtil.create("Model");')
    j(f'model.label("{CLASS}.mph");')
    j('model.comments("XAMS TPC electric field, generated by optical_sim/efield/comsol/make_model.py from geometry.yaml '
      'and efield/cases.yaml. Do not edit by hand: change the YAML files and regenerate.");')
    # ---------------------------------------------------------------- parameters (first case as default values)
    c0 = cases[names[0]]
    par = [("Va", c0["A"], "anode"), ("Vg", c0["G"], "gate"), ("Vc", c0["C"], "cathode"), ("Vbs", c0["BS"], "bottom screen"),
           ("Vts", c0["TS"], "top screen"), ("Vpt", c0["PMT_T"], "top PMT body"), ("Vpb", c0["PMT_B"], "bottom PMT body"),
           ("Vsipm", c0["SIPM"], "SiPM planes")]
    for n, v, d in par:
        j(f'model.param().set("{n}", "{v}[V]", "{d}");')
    j('model.param().set("icase", "1", "case index (auxiliary sweep)");')
    R = C["field_cage"]["resistors_gohm"]
    for i, r in enumerate(R, 1):
        j(f'model.param().set("R{i}", "{r}[Gohm]", "chain resistor {i}");')
    rsum = "(" + "+".join(f"R{i}" for i in range(1, 6)) + ")"
    for k in range(1, 5):
        part = "(" + "+".join(f"R{i}" for i in range(1, k + 1)) + ")"
        j(f'model.param().set("Vr{k}", "Vg+(Vc-Vg)*{part}/{rsum}", "field-shaping ring {k}");')
    j(f'model.param().set("Ichain", "(Vg-Vc)/{rsum}", "chain current");')

    # ---------------------------------------------------------------- geometry
    j('model.component().create("comp1", true);')
    j('GeomSequence g = model.component("comp1").geom().create("geom1", 3);')
    j('g.lengthUnit("mm");')

    def cyl(tag, r, z0, z1, sel=True):
        j(f'g.create("{tag}", "Cylinder").set("r", {r:.6g}).set("h", {z1 - z0:.6g}).set("pos", {jdbl([0, 0, z0])});')
        if sel:
            j(f'g.feature("{tag}").set("selresult", "on");')

    def block(tag, cx, cy, cz, sx, sy, sz, sel=True):
        j(f'g.create("{tag}", "Block").set("base", "center").set("pos", {jdbl([cx, cy, cz])}).set("size", {jdbl([sx, sy, sz])});')
        if sel:
            j(f'g.feature("{tag}").set("selresult", "on");')

    def diff(tag, a_, b_, keep=False, sel=True):
        j(f'g.create("{tag}", "Difference");')
        j(f'g.feature("{tag}").selection("input").set({jstr(a_)});')
        j(f'g.feature("{tag}").selection("input2").set({jstr(b_)});')
        if keep:
            j(f'g.feature("{tag}").set("keepsubtract", true);')
        if sel:
            j(f'g.feature("{tag}").set("selresult", "on");')

    def disc(tag, z, r):
        j(f'g.create("{tag}", "WorkPlane").set("quickz", {z:.6g}).set("unite", true);')
        j(f'g.feature("{tag}").geom().create("c1", "Circle").set("r", {r:.6g});')
        j(f'g.feature("{tag}").set("selresult", "on");')

    cyl("vessel", r_ves, ves_bot, ves_bot + ves_h)
    cyl("bko", bk["outer_diameter_mm"] / 2, bk_bottom, rim, sel=False)
    cyl("bki", bk["inner_diameter_mm"] / 2, bk_bottom + bk_t, rim, sel=False)
    diff("bucket", ["bko"], ["bki"])
    cyl("lxe", bk["inner_diameter_mm"] / 2, bk_bottom + bk_t, level)
    # meshes: discs + support rings
    conductors = {}
    for n, tag in (("top_screen", "ts"), ("anode", "an"), ("gate", "ga"), ("cathode", "ca"), ("bottom_screen", "bs")):
        m = meshes[n]
        z = m["z_mm"]
        z0, z1 = (z - t_ring, z) if m["foil_side"] == "up" else (z, z + t_ring)
        cyl(f"{tag}o", r_ring, z0, z1, sel=False)
        cyl(f"{tag}i", r_bore, z0, z1, sel=False)
        diff(f"ring_{tag}", [f"{tag}o"], [f"{tag}i"])
        disc(f"foil_{tag}", z, r_bore)
        conductors[tag] = [f"geom1_ring_{tag}_bnd", f"geom1_foil_{tag}_bnd"]
    # field-shaping rings
    for k, zr in enumerate(fsr["z_center_mm"], 1):
        cyl(f"f{k}o", fsr["outer_diameter_mm"] / 2, zr - t_fsr / 2, zr + t_fsr / 2, sel=False)
        cyl(f"f{k}i", fsr["inner_diameter_mm"] / 2, zr - t_fsr / 2, zr + t_fsr / 2, sel=False)
        diff(f"fsr{k}", [f"f{k}o"], [f"f{k}i"])
        conductors[f"r{k}"] = [f"geom1_fsr{k}_bnd"]
    # PTFE cylinder (+ SiPM holes)
    cyl("pto", r_ptfe_out, z_ptfe_bot, 0.0, sel=False)
    cyl("pti", r_ptfe_in, z_ptfe_bot, 0.0, sel=False)
    sipm_tags, hole_tags = [], []
    if not a.no_sipm:
        s, rec = sp["size_mm"], sp["recess_mm"]
        for i, phi in enumerate(sp["azimuth_deg"], 1):
            block(f"h{i}", r_ptfe_in + rec / 2, 0, sp["z_mm"], rec, s, s, sel=False)
            block(f"s{i}", r_ptfe_in + rec + 0.25, 0, sp["z_mm"], 0.5, s, s, sel=False)
            for o in (f"h{i}", f"s{i}"):
                j(f'g.create("rot_{o}", "Rotate").set("rot", "{phi:.6g}");')
                j(f'g.feature("rot_{o}").selection("input").set({jstr([o])});')
                j(f'g.feature("rot_{o}").set("selresult", "on");')
            hole_tags.append(f"rot_h{i}")
            sipm_tags.append(f"rot_s{i}")
        diff("ptfe0", ["pto"], ["pti"], sel=False)
        diff("ptfe", ["ptfe0"], hole_tags, keep=True)
        conductors["sipm"] = [f"geom1_{t}_bnd" for t in sipm_tags]
    else:
        diff("ptfe", ["pto"], ["pti"])
    # PMTs and their PTFE holders
    zt_win, zb_win = pz["top"], pz["bottom"]
    z_ts_body = meshes["top_screen"]["z_mm"] + t_ring
    z_bs_body = meshes["bottom_screen"]["z_mm"] - t_ring
    block("pmt_t", 0, 0, zt_win + h_pmt / 2, s_pmt, s_pmt, h_pmt)
    block("pmt_b", 0, 0, zb_win - h_pmt / 2, s_pmt, s_pmt, h_pmt)
    conductors["pmt_t"] = ["geom1_pmt_t_bnd"]
    conductors["pmt_b"] = ["geom1_pmt_b_bnd"]
    cyl("hto", ph["outer_diameter_mm"] / 2, z_ts_body, zt_win + h_pmt, sel=False)
    block("hts", 0, 0, zt_win + h_pmt / 2, s_pmt, s_pmt, h_pmt, sel=False)
    block("hta", 0, 0, (z_ts_body + zt_win) / 2, ap50, ap50, zt_win - z_ts_body, sel=False)
    diff("hold_t", ["hto"], ["hts", "hta"])
    cyl("hbo", ph["outer_diameter_mm"] / 2, zb_win - h_pmt, z_bs_body, sel=False)
    block("hbs", 0, 0, zb_win - h_pmt / 2, s_pmt, s_pmt, h_pmt, sel=False)
    block("hba", 0, 0, (z_bs_body + zb_win) / 2, ap50, ap50, z_bs_body - zb_win, sel=False)
    diff("hold_b", ["hbo"], ["hbs", "hba"])
    j("g.run();")

    # ---------------------------------------------------------------- selections
    def union(tag, dim, inputs):
        j(f'model.component("comp1").selection().create("{tag}", "Union");')
        j(f'model.component("comp1").selection("{tag}").set("entitydim", {dim});')
        j(f'model.component("comp1").selection("{tag}").set("input", {jstr(inputs)});')

    union("sel_ptfe", 3, ["geom1_ptfe_dom", "geom1_bucket_dom", "geom1_hold_t_dom", "geom1_hold_b_dom"])
    metal = [f"geom1_ring_{t}_dom" for t in ("ts", "an", "ga", "ca", "bs")] + [f"geom1_fsr{k}_dom" for k in range(1, 5)] \
        + ["geom1_pmt_t_dom", "geom1_pmt_b_dom"] + [f"geom1_{t}_dom" for t in sipm_tags]
    union("sel_metal", 3, metal)
    def adjacent(tag, dom):
        j(f'model.component("comp1").selection().create("{tag}", "Adjacent");')
        j(f'model.component("comp1").selection("{tag}").set("input", {jstr([dom])});')

    # solid objects only expose their domains: their surfaces come from Adjacent selections (exterior boundaries)
    made = set()
    for name, inp in conductors.items():
        ins = []
        for t in inp:
            if t.endswith("_bnd") and not t.startswith("geom1_foil_"):
                base = t[6:-4]
                if base not in made:
                    adjacent(f"adj_{base}", f"geom1_{base}_dom")
                    made.add(base)
                ins.append(f"adj_{base}")
            else:
                ins.append(t)
        union(f"c_{name}", 2, ins)
    adjacent("adj_vessel", "geom1_vessel_dom")
    adjacent("adj_ptfe", "geom1_ptfe_dom")
    j('model.component("comp1").selection().create("tpcin", "Cylinder");')
    j('model.component("comp1").selection("tpcin").set("entitydim", 3);')
    j(f'model.component("comp1").selection("tpcin").set("r", {r_bore + 0.01:.6g});')
    j(f'model.component("comp1").selection("tpcin").set("top", 0.01);')
    j(f'model.component("comp1").selection("tpcin").set("bottom", {zc - 0.01:.6g});')
    j('model.component("comp1").selection("tpcin").set("condition", "inside");')

    # ---------------------------------------------------------------- materials (later ones override earlier ones)
    def material(tag, label, eps, sel):
        j(f'model.component("comp1").material().create("{tag}", "Common");')
        j(f'model.component("comp1").material("{tag}").label("{label}");')
        j(f'model.component("comp1").material("{tag}").propertyGroup("def").set("relpermittivity", {jstr([eps])});')
        if sel == "all":
            j(f'model.component("comp1").material("{tag}").selection().all();')
        else:
            j(f'model.component("comp1").material("{tag}").selection().named("{sel}");')

    material("m_gxe", "gas xenon", "1.00", "all")
    material("m_lxe", "liquid xenon", "1.96", "geom1_lxe_dom")
    material("m_ptfe", "PTFE", "2.1", "sel_ptfe")
    material("m_metal", "metal (conductors)", "1", "sel_metal")

    # ---------------------------------------------------------------- physics
    j('model.component("comp1").physics().create("es", "Electrostatics", "geom1");')
    j('model.component("comp1").physics("es").create("gnd_vessel", "Ground", 2);')
    j('model.component("comp1").physics("es").feature("gnd_vessel").selection().named("adj_vessel");')
    vmap = {"ts": "Vts", "an": "Va", "ga": "Vg", "ca": "Vc", "bs": "Vbs", "r1": "Vr1", "r2": "Vr2", "r3": "Vr3", "r4": "Vr4",
            "pmt_t": "Vpt", "pmt_b": "Vpb", "sipm": "Vsipm"}
    for name in conductors:
        j(f'model.component("comp1").physics("es").create("pot_{name}", "ElectricPotential", 2);')
        j(f'model.component("comp1").physics("es").feature("pot_{name}").selection().named("c_{name}");')
        j(f'model.component("comp1").physics("es").feature("pot_{name}").set("V0", "{vmap[name]}");')

    # ---------------------------------------------------------------- mesh
    j('MeshSequence m = model.component("comp1").mesh().create("mesh1");')
    j('m.feature("size").set("custom", "on");')
    j(f'm.feature("size").set("hmax", {a.hmax:.6g});')
    j('m.feature("size").set("hmin", 0.05);')
    j('m.feature("size").set("hgrad", 1.35);')

    def msize(tag, dim, sel, hmax):
        j(f'm.create("{tag}", "Size");')
        j(f'm.feature("{tag}").selection().geom("geom1", {dim});')
        j(f'm.feature("{tag}").selection().named("{sel}");')
        j(f'm.feature("{tag}").set("custom", "on");')
        j(f'm.feature("{tag}").set("hmaxactive", true);')
        j(f'm.feature("{tag}").set("hmax", {hmax:.6g});')

    msize("sz_tpc", 3, "tpcin", a.hmax_tpc)
    msize("sz_ptfe", 2, "adj_ptfe", min(1.0, a.hmax_tpc))
    if sipm_tags:
        union("sel_holes", 3, [f"geom1_{t}_dom" for t in hole_tags])
        msize("sz_sipm", 3, "sel_holes", a.hmax_sipm)
        msize("sz_sipmb", 2, "c_sipm", a.hmax_sipm)
    j('m.create("ftet1", "FreeTet");')
    j("m.run();")
    j('System.out.println("CHECK mesh elements=" + m.getNumElem());')

    # ---------------------------------------------------------------- study: auxiliary sweep over the cases
    keys = [("Va", "A"), ("Vg", "G"), ("Vc", "C"), ("Vbs", "BS"), ("Vts", "TS"), ("Vpt", "PMT_T"), ("Vpb", "PMT_B"), ("Vsipm", "SIPM")]
    j('model.study().create("std1");')
    j('model.study("std1").create("stat", "Stationary");')
    j('model.study("std1").feature("stat").set("useparam", true);')
    j('model.study("std1").feature("stat").set("sweeptype", "sparse");')
    j(f'model.study("std1").feature("stat").set("pname", {jstr([k for k, _ in keys] + ["icase"])});')
    rows = [" ".join(str(cases[n][c]) for n in names) for _, c in keys] + [" ".join(str(i + 1) for i in range(len(names)))]
    j(f'model.study("std1").feature("stat").set("plistarr", {jstr(rows)});')
    j(f'model.study("std1").feature("stat").set("punit", {jstr(["V"] * len(keys) + [""])});')
    j('model.study("std1").run();')

    # ---------------------------------------------------------------- checks (printed) and exports
    L = abs(zc)
    zmid = zc / 2
    zs = sp["z_mm"]
    pts = {"centre": (0, 0, zmid), "r20": (20, 0, zmid), "liq_gap": (0, 0, level / 2), "gas_gap": (0, 0, (level + 8) / 2),
           "near_cathode": (0, 0, zc + 2), "near_gate": (0, 0, -2)}
    phi_far = (sp["azimuth_deg"][0] + 225) % 360
    pts["wall_sipm_height"] = (30.5 * math.cos(math.radians(phi_far)), 30.5 * math.sin(math.radians(phi_far)), zs)
    pts["axis_sipm_height"] = (0, 0, zs)
    if sipm_tags:
        for i, phi in enumerate(sp["azimuth_deg"], 1):
            for lab, rr in (("mouth", r_ptfe_in), ("front1mm", r_ptfe_in - 1), ("front3mm", r_ptfe_in - 3)):
                pts[f"sipm{i}_{lab}"] = (rr * math.cos(math.radians(phi)), rr * math.sin(math.radians(phi)), zs)
    pn = list(pts)
    xs, ys, zz = ([pts[p][k] for p in pn] for k in range(3))
    j('model.result().numerical().create("chk", "Interp");')
    j('model.result().numerical("chk").set("expr", new String[]{"V", "es.Ex", "es.Ey", "es.Ez", "es.normE"});')
    j('model.result().numerical("chk").set("coord", new double[][]{' + ", ".join(jdbl(v)[12:] for v in (xs, ys, zz)) + '});')
    j('double[][][] d = model.result().numerical("chk").getData();')
    j(f'String[] pn = {jstr(pn)};')
    j(f'String[] cn = {jstr(names)};')
    j("for (int s = 0; s < cn.length; s++) for (int p = 0; p < pn.length; p++)")
    j('  System.out.println("CHECK case=" + cn[s] + " point=" + pn[p] + " V=" + d[0][s][p] + " Ex=" + d[1][s][p] + " Ey=" + d[2][s][p] + " Ez=" + d[3][s][p] + " normE=" + d[4][s][p]);')
    j('System.out.println("CHECK chain_current_nA=" + model.param().evaluate("Ichain") * 1e9);')

    # exports (need COMSOL Preferences > Security > File system access: All files)
    def frange(lo, hi, st):
        n = int(round((hi - lo) / st)) + 1
        return [lo + i * st for i in range(n)]

    xr = frange(-36, 36, 0.2)
    zr = frange(zc - 8, 12, 0.2)
    # (r, z) plane through the first SiPM (azimuth phi1, r > 0) and on through the axis (r < 0 = phi1 + 180 deg):
    # evaluated with Interp and printed (MAP lines), so no file-system permission is needed
    phi1 = math.radians(sp["azimuth_deg"][0])
    nr, nz = 361, int(round((12 - (zc - 8)) / 0.2)) + 1
    j(f"int nr = {nr}, nz = {nz};")
    j("double[][] crd = new double[3][nr * nz];")
    j("for (int i = 0; i < nr; i++) for (int k = 0; k < nz; k++) {")
    j(f"  double r = -36.0 + 0.2 * i, z = {zc - 8:.6g} + 0.2 * k;")
    j(f"  crd[0][i * nz + k] = r * {math.cos(phi1):.9f}; crd[1][i * nz + k] = r * {math.sin(phi1):.9f}; crd[2][i * nz + k] = z;")
    j("}")
    j('model.result().numerical().create("map", "Interp");')
    j('model.result().numerical("map").set("expr", new String[]{"V", "es.Ex", "es.Ey", "es.Ez"});')
    j('model.result().numerical("map").set("coorderr", "off");')
    j('model.result().numerical("map").set("coord", crd);')
    j('double[][][] mp = model.result().numerical("map").getData();')
    j(f"double cp = {math.cos(phi1):.9f}, sp1 = {math.sin(phi1):.9f};")
    j("for (int s = 0; s < cn.length; s++) {")
    j('  StringBuilder sb = new StringBuilder();')
    j("  for (int p = 0; p < crd[0].length; p++) {")
    j("    double r = crd[0][p] * cp + crd[1][p] * sp1;")
    j('    sb.append("MAP ").append(cn[s]).append(" ").append((float) r).append(" ").append((float) crd[2][p]).append(" ")'
      '.append((float) mp[0][s][p]).append(" ").append((float) (mp[1][s][p] * cp + mp[2][s][p] * sp1)).append(" ").append((float) mp[3][s][p]).append("\\n");')
    j("  }")
    j("  System.out.print(sb);")
    j("}")
    j("try {")
    for si, n in enumerate(names, 1):
        exp = cases[n].get("export", [])
        if False:
            for plane, gx, gy in (("y0", xr, [0.0]), ("x0", [0.0], xr)):
                tag = f"e_{n}_{plane}"
                j(f'  model.result().export().create("{tag}", "Data");')
